//! The Apple M3 Max's `f32` reciprocal of a level's size, which its first computed level's
//! coordinates (and every level's of a 3D texture) start from.
//!
//! An Apple M4 computes `1 / w` rounded to nearest even. The M3 Max's GPU computes it as a kernel's
//! fast-math `1.0f / n` does (every `n` from 1 to 16384, the same in each
//! run), which is one unit in the last place above the rounded quotient at 1505 of those sizes and
//! one below at 26: the sizes below. A reciprocal's mantissa is that of the size's odd part, and
//! so is the M3 Max's deviation (measured at every size), so the tables list odd parts. Metal's
//! textures are at most 16384 texels along an axis, so these are every size a level has.

/// The GPU whose reciprocal a level's coordinates start from.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(super) enum Reciprocal {
    /// The Apple M3 Max: the tables below.
    AppleM3Max,
    /// The Apple M4: rounded to nearest even.
    AppleM4,
}

impl Reciprocal {
    /// `1 / n` (`n >= 1`) as the GPU computes it.
    pub(super) fn of(self, n: u32) -> f32 {
        let rounded = 1.0f32 / n as f32;
        if self == Reciprocal::AppleM4 {
            return rounded;
        }
        let odd = n >> n.trailing_zeros();
        let Ok(odd) = u16::try_from(odd) else {
            return rounded;
        };
        if M3_ABOVE.binary_search(&odd).is_ok() {
            f32::from_bits(rounded.to_bits() + 1)
        } else if M3_BELOW.binary_search(&odd).is_ok() {
            f32::from_bits(rounded.to_bits() - 1)
        } else {
            rounded
        }
    }
}

