//! A point's square, measured (on an Apple M4 under macOS 27.0.1, our probes
//! likewise; each case in a process of its own, two rounds alike): a 2048 by 64 single-sampled
//! frame (64 by 2 tiles), a `DontCare`-loaded, stored color attachment
//! prefilled with 0x11 bytes, one point a case, its centre and size as the probe computed them
//! (in `f64`, rounded to `f32`), and the tile columns of each tile row it reached. Our own probes;
//! their cases: the right, left, top and bottom edges against a tile's at sizes about 1.3 pixels,
//! 0 to 30000.5 units (of 1/256 of a pixel) of half size and on the ties of the rounding of the
//! size to 1/16 of a pixel, at x = 64 and x = 1024; large sizes and their clamp; centres past the
//! viewport.

use super::reference::Raster;
use super::{clip_in, points, Row};

/// The probes' frame, in pixels.
const FRAME: [u32; 2] = [2048, 64];

/// A case of `probe`: a point at `(x, y)` of `size` pixels, and the tile columns each tile row
/// reached.
fn wide(
    probe: &'static str,
    name: &'static str,
    x: f64,
    y: f64,
    size: f64,
    reached: [&[u32]; 2],
) -> Row {
    let tiles = reached.map(|cols| {
        (0..FRAME[0] / 32)
            .map(|c| if cols.contains(&c) { 'R' } else { '.' })
            .collect::<String>()
    });
    let reached = tiles.join(" ");
    let mut row = super::row(probe, name, points(vec![clip_in(FRAME, x, y, 0.5)]));
    row.raster = Raster::over(FRAME);
    row.size(size).reaches(&[reached.as_str()])
}

