//! The kernel on a device: the fixture of passes and the rule's answers
//! (`validation/fixtures/public/tile_reach/device_passes.txt`) that the validation crate's lane
//! `runtime_lane::tile_reach_kernel` dispatches on the device its cfg selects and compares bit for
//! bit. The passes hold every measured case drawn (directly or indirectly), each case under a
//! state of its own and in a slice of its own, grouped by render area and samples, and seeded
//! random passes ([`random_pass`]). Here the committed fixture is checked to be the rule's
//! answers for them, and the kernel's through the interpreter.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use super::kernel::{cull, random_pass, winding, Drawn, Pass, Rng};
use super::{measured, points, Draw};
use crate::bind::tile_reach::kernel::typed_module;
use crate::bind::tile_reach::TileReachModule as M;

/// The fixture, from this crate's directory.
const FIXTURE: &str = "../metal2vulkan-validation/fixtures/public/tile_reach/device_passes.txt";

/// The command that prints the fixture between [`BEGIN`] and [`END`].
const PRINT: &str = "cargo nextest run -p metal2vulkan --all-features --lib --run-ignored \
                     ignored-only --no-capture -E 'test(/print_the_device_passes/)'";

const BEGIN: &str = "----- device_passes.txt begins -----";
const END: &str = "----- device_passes.txt ends -----";

/// The random passes beside the measured cases.
const RANDOM_PASSES: usize = 16;

/// The passes: the measured cases drawn, one pass per render area and samples (each case's
/// primitives in a slice of their own, under its state; slice 0 holds none), then
/// [`RANDOM_PASSES`] seeded random passes of 32 primitives.
fn device_passes() -> Vec<Pass> {
    let mut rows = measured::rows();
    rows.extend(measured::later_rows());
    rows.extend(points::rows());
    let mut groups: BTreeMap<([u32; 2], u32), Pass> = BTreeMap::new();
    for row in rows
        .iter()
        .filter(|r| matches!(r.draw, Draw::Direct | Draw::Indirect))
    {
        let (area, samples) = (row.raster.area, row.raster.samples);
        let pass = groups.entry((area, samples)).or_insert_with(|| Pass {
            area,
            samples,
            layers: 1,
            states: Vec::new(),
            drawn: Vec::new(),
        });
        let state = pass.states.len() as u32;
        pass.states.push(row.raster);
        let layer = pass.layers;
        pass.layers += 1;
        let drawn = row.primitives().into_iter();
        pass.drawn
            .extend(drawn.map(|prim| Drawn::of(prim, state, layer)));
    }
    let mut passes: Vec<Pass> = groups.into_values().collect();
    let mut rng = Rng(0xde71_ce5e);
    let areas = [
        [128, 128],
        [96, 64],
        [200, 72],
        [33, 31],
        [256, 40],
        [160, 96],
    ];
    for _ in 0..RANDOM_PASSES {
        let area = rng.pick(&areas);
        let samples = rng.pick(&[1, 2, 4, 3]);
        passes.push(random_pass(&mut rng, area, samples, 32));
    }
    passes
}

/// Little-endian bytes as words, in hex.
fn hex(bytes: &[u8]) -> String {
    let words: Vec<String> = bytes
        .as_chunks::<4>()
        .0
        .iter()
        .map(|w| format!("{:08x}", u32::from_le_bytes(*w)))
        .collect();
    words.join(" ")
}

/// The fixture's text for `passes` (its header states the format).
fn fixture(passes: &[Pass]) -> String {
    let mut out = String::new();
    out.push_str(
        "# The tile reach kernel on a device: passes and the\n\
         # rule's answers, generated by bind::tile_reach::tests::device from the measured cases\n\
         # and seeded random passes. Our own synthetic data. Print it again with\n",
    );
    let _ = writeln!(out, "#   {PRINT}");
    out.push_str(
        "# Per pass: `pass <width> <height> <samples> <layers>`; each state, `state` and its 12\n\
         # words (TileReachModule::state); each primitive, `primitive` and its 16 words\n\
         # (TileReachModule::primitive), words in hex; `expect <near-far> <unmeasured>`, the\n\
         # header's two counts; and the tile mask's set bits, `bits` and up to 16 indices a line.\n",
    );
    for pass in passes {
        let [w, h] = pass.area;
        let _ = writeln!(out, "pass {w} {h} {} {}", pass.samples, pass.layers);
        for s in &pass.states {
            let words = M::state(
                s.viewport,
                s.scissor,
                cull(s.cull),
                winding(s.winding),
                u32::from(s.clamp),
            );
            let _ = writeln!(out, "state {}", hex(&words));
        }
        for d in &pass.drawn {
            let _ = writeln!(out, "primitive {}", hex(&d.record()));
        }
        let rule = pass.rule();
        let _ = writeln!(out, "expect {} {}", rule.near_far, rule.unmeasured);
        let [gx, gy] = pass.grid();
        let mut bits = Vec::new();
        for (slice, tiles) in rule.slices.iter().enumerate() {
            for [x, y] in tiles {
                bits.push((slice as u32 * gy + y) * gx + x);
            }
        }
        bits.sort_unstable();
        for line in bits.chunks(16) {
            let line: Vec<String> = line.iter().map(u32::to_string).collect();
            let _ = writeln!(out, "bits {}", line.join(" "));
        }
    }
    out
}

/// The committed fixture is the rule's answers for the passes, and the kernel bins each pass as
/// the rule does through the interpreter (both invocation orders).
#[test]
fn the_device_passes_are_the_rules_answers_and_the_kernels() {
    let passes = device_passes();
    let m = typed_module().expect("module");
    let wrong: Vec<String> = passes.iter().flat_map(|p| p.differences(&m)).collect();
    assert!(wrong.is_empty(), "{}", wrong.join("\n"));
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(FIXTURE);
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == fixture(&passes),
        "{FIXTURE} is not the rule's answers: print it with\n  {PRINT}\nand write the lines \
         between `{BEGIN}` and `{END}` to it"
    );
}

/// Print the fixture between [`BEGIN`] and [`END`] (the module docs).
#[test]
#[ignore = "prints the device fixture"]
fn print_the_device_passes() {
    println!("{BEGIN}\n{}{END}", fixture(&device_passes()));
}
